#!/usr/bin/env python3
"""Summarise the hardening audit: rank deltas, paired comparisons, validity.

    python3 redteam/hardening/analyze.py

Reads redteam/hardening/scores_{train,test}_cohort.json and
scoring/reference.json; writes redteam/hardening/summary.{json,md}.
Rank delta for a candidate c against the reference r over a population P:

    dR = sum_experiments weight * sum_metrics |coef| * dir * (c - r) / std_P(metric)

with dir = +1 when higher is better, -1 otherwise, population std (ddof=0),
metrics constant across P contribute 0.  Pure Python (no numpy).
"""

from __future__ import annotations

import json
import math
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
REFERENCE = "quasi_fresnel"


def metric_specs(reference: dict) -> list[tuple[str, str, float, float, int]]:
    specs = []
    for exp, payload in reference["experiments"].items():
        for metric, spec in payload["metrics"].items():
            specs.append((exp, metric, float(payload["weight"]), abs(float(spec["coefficient"])),
                          1 if spec["higher_is_better"] else -1))
    return specs


def values(scores: dict, name: str, specs) -> dict[tuple[str, str], float]:
    return {(e, m): float(scores["experiments"][e]["results"][name][m]) for e, m, *_ in specs}


def pop_std(xs: list[float]) -> float:
    return statistics.pstdev(xs) if len(xs) > 1 else 0.0


def rank_delta(scores: dict, cand: str, population: list[str], specs) -> float:
    ref = values(scores, REFERENCE, specs)
    c = values(scores, cand, specs)
    total = 0.0
    for e, m, w, coef, direction in specs:
        sd = pop_std([values(scores, p, specs)[(e, m)] for p in population])
        if sd > 0:
            total += w * coef * direction * (c[(e, m)] - ref[(e, m)]) / sd
    return total


def paired(scores: dict, cand: str, specs, population: list[str]) -> dict:
    det = scores.get("_details", {})
    ref_d, cand_d = det.get(REFERENCE, {}), det.get(cand, {})
    common = sorted(set(ref_d) & set(cand_d))
    out: dict = {"scenes": len(common)}
    if not common:
        return out
    quality = [(e, m, w, c, d) for e, m, w, c, d in specs if m != "peak_memory_mb"]
    sds = {}
    for e, m, w, coef, d in specs:
        sds[(e, m)] = pop_std([values(scores, p, specs)[(e, m)] for p in population])
    per_scene_q = []
    for sid in common:
        total = 0.0
        for e, m, w, coef, d in quality:
            if sds[(e, m)] > 0:
                total += w * coef * d * (cand_d[sid][m] - ref_d[sid][m]) / sds[(e, m)]
        per_scene_q.append(total)
    for e, m, w, coef, d in specs:
        key = "peak_rss_mb" if m == "peak_memory_mb" else m
        diffs = [d * (cand_d[sid][key] - ref_d[sid][key]) for sid in common]
        mean = statistics.fmean(diffs)
        se = statistics.stdev(diffs) / math.sqrt(len(diffs)) if len(diffs) > 1 else 0.0
        out[m] = {"mean_improvement": mean, "se": se, "t": (mean / se) if se > 0 else (math.inf if mean > 0 else (-math.inf if mean < 0 else 0.0)),
                  "scenes_improved": sum(1 for x in diffs if x > 0)}
    mean_q = statistics.fmean(per_scene_q)
    se_q = statistics.stdev(per_scene_q) / math.sqrt(len(per_scene_q)) if len(per_scene_q) > 1 else 0.0
    out["quality_rank_per_scene"] = {"mean": mean_q, "se": se_q,
                                     "t": (mean_q / se_q) if se_q > 0 else 0.0}
    return out


def table(scores: dict, specs, populations: dict[str, list[str]]) -> list[dict]:
    rows = []
    for name in sorted(scores["experiments"]["surface_reconstruction"]["results"]):
        v = values(scores, name, specs)
        st = scores["_status"][name]
        row = {"method": name, "valid": st["valid"], "failures": st["failures"]}
        row.update({m: v[(e, m)] for e, m, *_ in specs})
        for label, pop in populations.items():
            if name in pop:
                row[f"dR_{label}"] = rank_delta(scores, name, pop, specs)
        rows.append(row)
    return rows


def fmt(x, digits=3):
    if isinstance(x, float):
        if math.isinf(x):
            return "inf" if x > 0 else "-inf"
        return f"{x:+.{digits}f}" if digits and abs(x) < 1e4 else f"{x:.4g}"
    return str(x)


def main() -> None:
    reference = json.loads((ROOT / "scoring" / "reference.json").read_text())
    specs = metric_specs(reference)
    summary: dict = {}
    md = ["# Hardening audit summary (generated by redteam/hardening/analyze.py)", ""]
    for split in ("test", "train"):
        path = HERE / f"scores_{split}_cohort.json"
        if not path.exists():
            md.append(f"`{path.name}` missing.")
            continue
        scores = json.loads(path.read_text())
        if "_status" not in scores or "surface_reconstruction" not in scores.get("experiments", {}):
            md.append(f"`{path.name}` is not a hardened-evaluator score file; skipped.")
            continue
        names = sorted(scores["experiments"]["surface_reconstruction"]["results"])
        honest = [n for n in names if not n.startswith("sc_")]
        valid_honest = [n for n in honest if scores["_status"][n]["valid"]]
        populations = {"honest": honest, "all": names, "valid": valid_honest}
        rows = table(scores, specs, populations)
        pairs = {n: paired(scores, n, specs, honest) for n in names
                 if n != REFERENCE and scores["_status"][n]["valid"] and scores["_status"][REFERENCE]["valid"]}
        summary[split] = {"rows": rows, "paired_vs_reference": pairs, "populations": populations}

        md += [f"## {split} split", "",
               "| method | valid | depth MAE cm ↓ | albedo NCC ↑ | albedo PSNR dB ↑ | peak memory MB ↓ | ΔR honest | ΔR all | ΔR valid |",
               "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for r in rows:
            md.append(
                f"| {r['method']} | {'yes' if r['valid'] else 'no'} | {r['depth_mae_cm']:.4f} | {r['albedo_ncc']:.4f} | "
                f"{r['albedo_psnr_db']:.3f} | {r['peak_memory_mb']:.2f} | {fmt(r.get('dR_honest', float('nan')))} | "
                f"{fmt(r.get('dR_all', float('nan')))} | {fmt(r.get('dR_valid', float('nan'))) if 'dR_valid' in r else '—'} |")
        md += ["", "Failures:", ""]
        for r in rows:
            if not r["valid"]:
                md.append(f"- `{r['method']}`: {'; '.join(r['failures'])[:400]}")
        md += ["", f"Paired per-scene comparisons against `{REFERENCE}` ({split}; improvement direction, mean ± SE):", "",
               "| method | scenes | depth cm | NCC | PSNR dB | memory MB | quality ΔR/scene | t |",
               "|---|---:|---:|---:|---:|---:|---:|---:|"]
        for name, p in pairs.items():
            if not p.get("scenes"):
                continue
            q = p["quality_rank_per_scene"]
            md.append(
                f"| {name} | {p['scenes']} | {p['depth_mae_cm']['mean_improvement']:+.4f} ± {p['depth_mae_cm']['se']:.4f} | "
                f"{p['albedo_ncc']['mean_improvement']:+.4f} ± {p['albedo_ncc']['se']:.4f} | "
                f"{p['albedo_psnr_db']['mean_improvement']:+.3f} ± {p['albedo_psnr_db']['se']:.3f} | "
                f"{p['peak_memory_mb']['mean_improvement']:+.2f} ± {p['peak_memory_mb']['se']:.2f} | "
                f"{q['mean']:+.4f} ± {q['se']:.4f} | {q['t']:+.2f} |")
        md.append("")
    unc = HERE / "uncapped_diagnostics.json"
    if unc.exists():
        data = json.loads(unc.read_text())
        md += ["## Uncapped diagnostic (two visible 256 x 256 scenes, 24 GB ceiling)", "",
               "| method | scene | peak memory MB | depth MAE cm | NCC | PSNR dB | status |", "|---|---|---:|---:|---:|---:|---|"]
        for name, per in data.items():
            if name.startswith("_"):
                continue
            for sid, e in per.items():
                md.append(f"| {name} | {sid} | {e.get('peak_rss_mb', float('nan')):.1f} | {e.get('depth_mae_cm', float('nan')):.4f} | "
                          f"{e.get('albedo_ncc', float('nan')):.4f} | {e.get('albedo_psnr_db', float('nan')):.3f} | "
                          f"{e.get('killed') or e.get('error') or ('exit ' + str(e.get('exit_code')))} |")
        summary["uncapped"] = data
    (HERE / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    (HERE / "summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
