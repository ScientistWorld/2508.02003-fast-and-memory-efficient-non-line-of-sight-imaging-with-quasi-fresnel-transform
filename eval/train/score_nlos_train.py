#!/usr/bin/env python3
"""
Visible train-slice scorer for the NLOS benchmark.

The input contract matches scripts/evaluate.sh: read a method-produced JSON
report and write normalized scores. This train slice uses the public bunny
depth/efficiency report plus one visible albedo-quality triangulation metric
from the sibling diagnostics file generated by the method run.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from typing import Any


DEFAULT_METHOD_NAME = "quasi_fresnel_proposed"


def _load_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def _number(value: Any, name: str) -> float:
    if not isinstance(value, (int, float)):
        raise TypeError(f"Metric {name!r} must be numeric, got {type(value).__name__}")
    return float(value)


def _method_payload(report: dict[str, Any], experiment: str) -> tuple[str, dict[str, Any]]:
    experiments = report.get("experiments")
    if not isinstance(experiments, dict):
        raise ValueError("Input report must contain an 'experiments' object")
    exp_payload = experiments.get(experiment)
    if not isinstance(exp_payload, dict):
        raise ValueError(f"Missing experiment {experiment!r} in input report")
    results = exp_payload.get("results")
    if not isinstance(results, dict):
        raise ValueError(f"Experiment {experiment!r} must contain a 'results' object")
    method_name = DEFAULT_METHOD_NAME
    method_payload = results.get(method_name)
    if method_payload is None and len(results) == 1:
        method_name, method_payload = next(iter(results.items()))
    if not isinstance(method_payload, dict):
        raise ValueError(
            f"Experiment {experiment!r} is missing method {DEFAULT_METHOD_NAME!r} "
            "and does not contain exactly one fallback method"
        )
    return method_name, method_payload


def _diagnostics_path(input_path: Path) -> Path:
    override = os.environ.get("DIAGNOSTICS_PATH")
    if override:
        return Path(override)
    return input_path.parent / "diagnostics.json"


def _primary_quality(diagnostics: dict[str, Any]) -> dict[str, Any]:
    try:
        quality = diagnostics["primary_public_scene"]["traditional"]["quality"]
    except KeyError as exc:
        raise ValueError("Diagnostics are missing primary_public_scene.traditional.quality") from exc
    if not isinstance(quality, dict):
        raise ValueError("Diagnostics quality payload must be an object")
    return quality


def build_scores(report: dict[str, Any], diagnostics: dict[str, Any]) -> dict[str, Any]:
    method_name, depth = _method_payload(report, "zaragoza_bunny_depth_error")
    efficiency_method_name, efficiency = _method_payload(report, "zaragoza_efficiency_public_bunny")
    if efficiency_method_name != method_name:
        raise ValueError("Train-slice experiments report different method names")
    quality = _primary_quality(diagnostics)

    return {
        "experiments": {
            "zaragoza_bunny_depth_error": {
                "results": {
                    method_name: {
                        "depth_mae_cm": round(_number(depth.get("depth_mae_cm"), "depth_mae_cm"), 6),
                        "albedo_psnr_db": round(_number(quality.get("psnr"), "albedo_psnr_db"), 6),
                    }
                }
            },
            "zaragoza_efficiency_public_bunny": {
                "results": {
                    method_name: {
                        "runtime_s": round(_number(efficiency.get("runtime_s"), "runtime_s"), 6),
                        "memory_mb": round(_number(efficiency.get("memory_mb"), "memory_mb"), 6),
                    }
                }
            },
        }
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input",
        default="/home/user/scoring/raw_results.json",
        help="Method-produced benchmark report to score.",
    )
    parser.add_argument(
        "--output",
        default="/home/user/scoring/scores_train.json",
        help="Where to write normalized train-slice scores.",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)
    diagnostics_path = _diagnostics_path(input_path)

    report = _load_json(input_path)
    diagnostics = _load_json(diagnostics_path)
    scores = build_scores(report, diagnostics)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(scores, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {output_path}")


if __name__ == "__main__":
    main()
