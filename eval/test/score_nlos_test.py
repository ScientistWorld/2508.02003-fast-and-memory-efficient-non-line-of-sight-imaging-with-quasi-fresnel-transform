#!/usr/bin/env python3
"""
Held-out test-slice scorer for the NLOS benchmark.

The input contract matches scripts/evaluate.sh: read a method-produced JSON
report and write normalized scores. The hidden slice keeps the same public
bunny scalar targets but scores different quality and efficiency diagnostics
that are generated by the same method run.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from typing import Any


# Discover the method from the results — no hardcoded preference.


def _load_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def _number(value: Any, name: str) -> float:
    if not isinstance(value, (int, float)):
        raise TypeError(f"Metric {name!r} must be numeric, got {type(value).__name__}")
    return float(value)


def _method_payload(report: dict[str, Any], experiment: str) -> tuple[str, dict[str, Any]]:
    experiments = report.get("experiments")
    if not isinstance(experiments, dict):
        raise ValueError("Input report must contain an 'experiments' object")
    exp_payload = experiments.get(experiment)
    if not isinstance(exp_payload, dict):
        raise ValueError(f"Missing experiment {experiment!r} in input report")
    results = exp_payload.get("results")
    if not isinstance(results, dict):
        raise ValueError(f"Experiment {experiment!r} must contain a 'results' object")
    if len(results) != 1:
        raise ValueError(
            f"Experiment {experiment!r} must contain exactly one method result; "
            f"found {len(results)}: {list(results.keys())}"
        )
    method_name, method_payload = next(iter(results.items()))
    if not isinstance(method_payload, dict):
        raise ValueError(f"Method payload for {method_name!r} must be a dict")
    return method_name, method_payload


def _diagnostics_path(input_path: Path) -> Path:
    override = os.environ.get("DIAGNOSTICS_PATH")
    if override:
        return Path(override)
    return input_path.parent / "diagnostics.json"


def _primary_scene(diagnostics: dict[str, Any]) -> dict[str, Any]:
    scene = diagnostics.get("primary_public_scene")
    if not isinstance(scene, dict):
        raise ValueError("Diagnostics are missing primary_public_scene")
    return scene


def _complexity(diagnostics: dict[str, Any]) -> dict[str, Any]:
    complexity = diagnostics.get("complexity_scaling")
    if not isinstance(complexity, dict):
        raise ValueError("Diagnostics are missing complexity_scaling")
    return complexity


def build_scores(report: dict[str, Any], diagnostics: dict[str, Any]) -> dict[str, Any]:
    method_name, depth = _method_payload(report, "zaragoza_bunny_depth_error")
    efficiency_method_name, efficiency = _method_payload(report, "zaragoza_efficiency_public_bunny")
    if efficiency_method_name != method_name:
        raise ValueError("Held-out test experiments report different method names")
    scene = _primary_scene(diagnostics)
    complexity = _complexity(diagnostics)

    try:
        quality = scene["traditional"]["quality"]
        loading_consistency = scene["loading"]["consistency_vs_traditional"]
        traditional_scaling = complexity["traditional"]
        loading_scaling = complexity["loading"]
    except KeyError as exc:
        raise ValueError("Diagnostics are missing required held-out quality/scaling fields") from exc

    return {
        "experiments": {
            "zaragoza_bunny_depth_error": {
                "results": {
                    method_name: {
                        "depth_mae_cm": round(_number(depth.get("depth_mae_cm"), "depth_mae_cm"), 6),
                        "albedo_ssim": round(_number(quality.get("ssim"), "albedo_ssim"), 6),
                        "albedo_mae": round(_number(quality.get("albedo_mae"), "albedo_mae"), 6),
                    }
                }
            },
            "zaragoza_efficiency_public_bunny": {
                "results": {
                    method_name: {
                        "runtime_s": round(_number(efficiency.get("runtime_s"), "runtime_s"), 6),
                        "memory_mb": round(_number(efficiency.get("memory_mb"), "memory_mb"), 6),
                        "traditional_runtime_order": round(
                            _number(
                                traditional_scaling.get("runtime_order"),
                                "traditional_runtime_order",
                            ),
                            6,
                        ),
                        "loading_memory_order": round(
                            _number(loading_scaling.get("memory_order"), "loading_memory_order"),
                            6,
                        ),
                        "loading_depth_consistency_cm": round(
                            100.0
                            * _number(
                                loading_consistency.get("depth_mae"),
                                "loading_depth_consistency_cm",
                            ),
                            6,
                        ),
                    }
                }
            },
        }
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input",
        default="/home/user/scoring/raw_results.json",
        help="Method-produced benchmark report to score.",
    )
    parser.add_argument(
        "--output",
        default="/home/user/scoring/scores_test.json",
        help="Where to write normalized held-out test scores.",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)
    diagnostics_path = _diagnostics_path(input_path)

    report = _load_json(input_path)
    diagnostics = _load_json(diagnostics_path)
    scores = build_scores(report, diagnostics)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(scores, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {output_path}")


if __name__ == "__main__":
    main()
